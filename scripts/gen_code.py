"""Write UsdtVerify/Code/Bytes.lean, the runtime bytecode as one hexadecimal natural number."""
import sys

hexs = open(sys.argv[1]).read().strip().lower()
size = len(hexs) // 2
lines = [hexs[i:i + 96] for i in range(0, len(hexs), 96)]
out = ["-- Generated by scripts/gen_code.py from data/usdt.runtime.hex; do not edit.",
       "",
       "namespace UsdtVerify",
       "",
       "/-- The runtime bytecode of USDT as one big-endian natural number. -/",
       "def CODE_NAT : Nat :=",
       "  0x" + lines[0] + "\\"]
# A string gap is not available for numerals, so the number is written on one line.
out = out[:-1]
out.append("  0x" + hexs)
out += ["", f"/-- The number of bytes of the runtime bytecode. -/",
        f"def CODE_SIZE : Nat := {size}", "", "end UsdtVerify", ""]
open(sys.argv[2], "w").write("\n".join(out))
print(size)
