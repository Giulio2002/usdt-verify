"""Write UsdtVerify/Usdt/Code/Bytes.lean, the runtime bytecode as one hexadecimal natural number."""
import sys

hexs = open(sys.argv[1]).read().strip().lower()
size = len(hexs) // 2
# A string gap is not available for numerals, so the number is written on one line.
out = ["-- Generated by scripts/gen_code.py from data/usdt.runtime.hex; do not edit.",
       "",
       "/-!",
       "# The bytes of the runtime bytecode",
       "",
       "Defines `CODE_NAT`, the runtime bytecode of USDT as one natural number, and `CODE_SIZE`, its",
       "number of bytes; `Usdt/Code.lean` turns them into the byte array `CODE`.",
       "-/",
       "",
       "namespace UsdtVerify",
       "",
       "/-- The runtime bytecode of USDT as one big-endian natural number. -/",
       "def CODE_NAT : Nat :=",
       "  0x" + hexs,
       "", "/-- The number of bytes of the runtime bytecode. -/",
       f"def CODE_SIZE : Nat := {size}", "", "end UsdtVerify", ""]
open(sys.argv[2], "w").write("\n".join(out))
print(size)
